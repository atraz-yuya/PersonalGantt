import Foundation
import Security
import CryptoKit
import X509

@MainActor final class LocalSyncKeychainPreferences: LocalSyncPreferenceStoring {
    private let service: String
    init(service: String = "com.atraz.PersonalGantt.local-sync") { self.service = service }
    private var query: [String: Any] {
        [kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service,
         kSecAttrAccount as String: "preferences", kSecAttrSynchronizable as String: false,
         kSecUseDataProtectionKeychain as String: true]
    }
    func load() throws -> LocalSyncPreferences {
        var request = query; request[kSecReturnData as String] = true; request[kSecMatchLimit as String] = kSecMatchLimitOne
        var result: CFTypeRef?
        let status = SecItemCopyMatching(request as CFDictionary, &result)
        if status == errSecItemNotFound { return LocalSyncPreferences() }
        guard status == errSecSuccess, let data = result as? Data, data.count < 16_384,
              let value = try? JSONDecoder().decode(LocalSyncPreferences.self, from: data), value.isValid else { throw LocalSyncError.storage }
        return value
    }
    func save(_ preferences: LocalSyncPreferences) throws {
        guard preferences.isValid else { throw LocalSyncError.storage }
        let data = try JSONEncoder().encode(preferences)
        let status = SecItemUpdate(query as CFDictionary, [kSecValueData as String: data] as CFDictionary)
        if status == errSecItemNotFound {
            var item = query; item[kSecValueData as String] = data
            item[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
            guard SecItemAdd(item as CFDictionary, nil) == errSecSuccess else { throw LocalSyncError.storage }
        } else if status != errSecSuccess { throw LocalSyncError.storage }
    }
}

/// One TLS identity per device. Keys are generated by Security and certificates
/// by Apple's X509 library; no embedded shared key or home-grown cryptography.
@MainActor enum LocalSyncIdentity {
    enum KeyAlgorithm { case legacyEC, rsa }
    /// Never change a previously pinned local identity behind a trusted peer's
    /// back. An old EC pairing must be explicitly removed on both devices first.
    static func requireCompatibleIdentity(deviceID: UUID, trusted: LocalTrustedDevice?) throws {
        guard trusted != nil else { return }
        let tag = Data(("com.atraz.PersonalGantt.local-sync.identity." + deviceID.uuidString + ".rsa-v2").utf8)
        let query: [String: Any] = [kSecClass as String: kSecClassKey,
            kSecAttrApplicationTag as String: tag, kSecAttrKeyClass as String: kSecAttrKeyClassPrivate,
            kSecAttrKeyType as String: kSecAttrKeyTypeRSA, kSecUseDataProtectionKeychain as String: true]
        let status = SecItemCopyMatching(query as CFDictionary, nil)
        if status == errSecItemNotFound { throw LocalSyncError.identityUpgrade }
        guard status == errSecSuccess else { throw LocalSyncError.storage }
        let certificateQuery: [String: Any] = [kSecClass as String: kSecClassCertificate,
            kSecAttrLabel as String: "com.atraz.PersonalGantt.local-sync.identity." + deviceID.uuidString + ".rsa-v2",
            kSecUseDataProtectionKeychain as String: true]
        let certificateStatus = SecItemCopyMatching(certificateQuery as CFDictionary, nil)
        if certificateStatus == errSecItemNotFound { throw LocalSyncError.identityUpgrade }
        guard certificateStatus == errSecSuccess else { throw LocalSyncError.storage }
    }
    static func load(deviceID: UUID, algorithm: KeyAlgorithm = .rsa) throws -> (SecIdentity, Data) {
        let rsa = algorithm == .rsa
        let keyType = rsa ? kSecAttrKeyTypeRSA : kSecAttrKeyTypeECSECPrimeRandom
        let label = "com.atraz.PersonalGantt.local-sync.identity." + deviceID.uuidString + (rsa ? ".rsa-v2" : "")
        let tag = Data(label.utf8)
        let keyQuery: [String: Any] = [kSecClass as String: kSecClassKey, kSecAttrApplicationTag as String: tag,
            kSecAttrKeyClass as String: kSecAttrKeyClassPrivate,
            kSecAttrKeyType as String: keyType, kSecUseDataProtectionKeychain as String: true,
            kSecReturnRef as String: true]
        var found: CFTypeRef?
        let status = SecItemCopyMatching(keyQuery as CFDictionary, &found)
        let key: SecKey
        if status == errSecItemNotFound {
            let attributes: [String: Any] = [kSecAttrKeyType as String: keyType,
                kSecAttrKeySizeInBits as String: rsa ? 2048 : 256, kSecUseDataProtectionKeychain as String: true,
                kSecPrivateKeyAttrs as String: [kSecAttrIsPermanent as String: true, kSecAttrApplicationTag as String: tag,
                    kSecAttrAccessible as String: kSecAttrAccessibleWhenUnlockedThisDeviceOnly]]
            guard let generated = SecKeyCreateRandomKey(attributes as CFDictionary, nil) else { throw LocalSyncError.storage }
            key = generated
        } else {
            guard status == errSecSuccess, let found, CFGetTypeID(found) == SecKeyGetTypeID() else { throw LocalSyncError.storage }
            key = (found as! SecKey)
        }
        let certificateQuery: [String: Any] = [kSecClass as String: kSecClassCertificate, kSecAttrLabel as String: label,
            kSecUseDataProtectionKeychain as String: true, kSecReturnRef as String: true]
        var stored: CFTypeRef?
        let certificateStatus = SecItemCopyMatching(certificateQuery as CFDictionary, &stored)
        let certificate: SecCertificate
        if certificateStatus == errSecItemNotFound {
            certificate = try makeCertificate(key: key, deviceID: deviceID)
            var item = certificateQuery; item.removeValue(forKey: kSecReturnRef as String)
            item[kSecValueRef as String] = certificate
            item[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
            guard SecItemAdd(item as CFDictionary, nil) == errSecSuccess else { throw LocalSyncError.storage }
        } else {
            guard certificateStatus == errSecSuccess, let stored, CFGetTypeID(stored) == SecCertificateGetTypeID() else { throw LocalSyncError.storage }
            certificate = (stored as! SecCertificate)
        }
        guard let identity = SecIdentityCreate(nil, certificate, key) else { throw LocalSyncError.storage }
        let hash = try validate(identity)
        LocalSyncDiagnostics.log("identity.validated", fingerprint: hash,
                                 detail: "algorithm=\(rsa ? "RSA2048" : "EC256") firstType=SecIdentity publicKeysMatch=true signatureVerified=true")
        return (identity, hash)
    }
    /// Runs on every live Keychain load, not just on newly generated keys.
    /// Only public key representations leave Security; private keys stay opaque.
    static func validate(_ identity: SecIdentity) throws -> Data {
        guard CFGetTypeID(identity) == SecIdentityGetTypeID() else { throw LocalSyncError.storage }
        var certificate: SecCertificate?
        var privateKey: SecKey?
        guard SecIdentityCopyCertificate(identity, &certificate) == errSecSuccess,
              SecIdentityCopyPrivateKey(identity, &privateKey) == errSecSuccess,
              let certificate, let privateKey, let fromCertificate = SecCertificateCopyKey(certificate),
              let fromPrivate = SecKeyCopyPublicKey(privateKey),
              let publicData = SecKeyCopyExternalRepresentation(fromPrivate, nil),
              let certificateData = SecKeyCopyExternalRepresentation(fromCertificate, nil),
              publicData as Data == certificateData as Data else { throw LocalSyncError.storage }
        let attributes = SecKeyCopyAttributes(privateKey) as? [String: Any]
        let rsa = attributes?[kSecAttrKeyType as String] as? String == kSecAttrKeyTypeRSA as String
        let algorithm: SecKeyAlgorithm = rsa ? .rsaSignatureMessagePKCS1v15SHA256 : .ecdsaSignatureMessageX962SHA256
        let challenge = Data(UUID().uuidString.utf8)
        guard SecKeyIsAlgorithmSupported(privateKey, .sign, algorithm),
              let signature = SecKeyCreateSignature(privateKey, algorithm, challenge as CFData, nil),
              SecKeyVerifySignature(fromCertificate, algorithm, challenge as CFData, signature, nil) else {
            throw LocalSyncError.storage
        }
        return Data(SHA256.hash(data: SecCertificateCopyData(certificate) as Data))
    }
    static func securityIdentity(_ identity: SecIdentity) throws -> [Any] {
        _ = try validate(identity)
        let values: [Any] = [identity]
        guard let first = values.first, CFGetTypeID(first as CFTypeRef) == SecIdentityGetTypeID() else {
            throw LocalSyncError.storage
        }
        return values
    }
    static func makeCertificate(key: SecKey, deviceID: UUID, now: Date = Date()) throws -> SecCertificate {
        let privateKey = try X509.Certificate.PrivateKey(key)
        let attributes = SecKeyCopyAttributes(key) as? [String: Any]
        let rsa = attributes?[kSecAttrKeyType as String] as? String == kSecAttrKeyTypeRSA as String
        let name = try DistinguishedName { CommonName(deviceID.uuidString) }
        let certificate = try X509.Certificate(version: .v3, serialNumber: .init(bytes: Array(SHA256.hash(data: Data(UUID().uuidString.utf8)).prefix(16))),
            publicKey: privateKey.publicKey, notValidBefore: now.addingTimeInterval(-300),
            notValidAfter: now.addingTimeInterval(10 * 366 * 24 * 3600), issuer: name, subject: name,
            extensions: X509.Certificate.Extensions {
                KeyUsage(digitalSignature: true, keyEncipherment: rsa, keyAgreement: !rsa)
            }, issuerPrivateKey: privateKey)
        return try SecCertificate.makeWithCertificate(certificate)
    }
}
